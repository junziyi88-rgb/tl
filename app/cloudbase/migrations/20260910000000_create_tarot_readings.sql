create table if not exists public.readings (
  id bigint generated by default as identity primary key,
  owner_id text not null default auth.uid(),
  author_name varchar(24) not null check (char_length(btrim(author_name)) between 1 and 24),
  question varchar(160) not null check (char_length(btrim(question)) between 1 and 160),
  mode varchar(8) not null check (mode in ('online', 'physical')),
  spread varchar(8) not null check (spread in ('one', 'three', 'five')),
  cards jsonb not null check (jsonb_typeof(cards) = 'array'),
  interpretation text not null check (char_length(btrim(interpretation)) between 1 and 4000),
  tags text[] not null default '{}'::text[] check (cardinality(tags) <= 3),
  feedback varchar(200) not null default '' check (feedback !~ E'[\r\n]'),
  idempotency_key uuid not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists readings_created_at_idx
  on public.readings (created_at desc);

create index if not exists readings_owner_id_idx
  on public.readings (owner_id);

alter table public.readings enable row level security;

revoke all on public.readings from anon, authenticated;
grant select, insert, delete on public.readings to anon;
grant update (feedback, updated_at) on public.readings to anon;
grant usage, select on sequence public.readings_id_seq to anon;
grant all on public.readings to service_role;
grant usage, select on sequence public.readings_id_seq to service_role;

drop policy if exists readings_select on public.readings;
create policy readings_select on public.readings
  for select to anon
  using (true);

drop policy if exists readings_insert_own on public.readings;
create policy readings_insert_own on public.readings
  for insert to anon
  with check (owner_id = (select auth.uid()));

drop policy if exists readings_update_own on public.readings;
create policy readings_update_own on public.readings
  for update to anon
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

drop policy if exists readings_delete_own on public.readings;
create policy readings_delete_own on public.readings
  for delete to anon
  using (owner_id = (select auth.uid()));
